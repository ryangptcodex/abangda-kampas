const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),{execFileSync}=require('node:child_process');
const root=path.join(__dirname,'..');const temp=fs.mkdtempSync(path.join(os.tmpdir(),'abangda-css-'));const output=path.join(temp,'compiled.css');
try {
 const cli=process.env.TAILWIND_CLI||require.resolve('tailwindcss/lib/cli.js');
 execFileSync(process.execPath,[cli,'-c','tailwind.config.cjs','-i','styles/input.css','-o',output,'--minify'],{cwd:root,stdio:'inherit'});
 const css=fs.readFileSync(output,'utf8');
 fs.writeFileSync(path.join(root,'css.html'),'<style>\n/* Generated by npm run build:css. No runtime Tailwind CDN required. */\n'+css+'\n</style>\n');
 console.log('Generated css.html ('+css.length+' CSS characters)');
}finally{fs.rmSync(temp,{recursive:true,force:true});}
